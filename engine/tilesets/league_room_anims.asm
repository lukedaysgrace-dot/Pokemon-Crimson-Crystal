; Ambient animation for the five Elite Four chambers.
;
; The chamber tileset animation tables (data/tilesets/league_room_anim_tables.asm,
; in the bank of _AnimateTileset) call LeagueRoomAnimTrampoline with de pointing
; at one descriptor below. Each call does one small job during VBlank:
;
;   LEAGUE_ANIM_TILE:    db LEAGUE_ANIM_TILE
;                        dw VRAM tile address (bank 0)
;                        db step mask (sequence length - 1, power of two)
;                        db speed (the 16-bit frame counter is shifted right this many times)
;                        dw frames (16 bytes each)
;                        dw sequence (frame index for each step)
;   LEAGUE_ANIM_PALETTE: db LEAGUE_ANIM_PALETTE, palette, LEAGUE_PAL_* mode
;
; Descriptors, frames and sequences are generated by tools/e4_rooms/build_all.py.

LEAGUE_ANIM_TILE    EQU 0
LEAGUE_ANIM_PALETTE EQU 1

LEAGUE_PAL_ROTATE  EQU 0 ; rotate colours 0-2
LEAGUE_PAL_PULSE   EQU 1 ; colour 0 steps through colours 0,1,2,1 (glints)
LEAGUE_PAL_FLICKER EQU 2 ; colours 0/1 swap on an irregular beat (flames)
LEAGUE_PAL_FLICKER_SLOW EQU 3 ; the same flicker at half speed


SECTION "League Room Anim Trampoline", ROM0

LeagueRoomAnimTrampoline::
; Jumped to from _AnimateTileset with de = descriptor. Stack-based bank
; switch (safe inside VBlank; no farcall buffers are touched).
	ldh a, [hROMBank]
	push af
	ld a, BANK(LeagueRoomAnim)
	rst Bankswitch
	call LeagueRoomAnim
	pop af
	rst Bankswitch
	ret


SECTION "League Room Animations", ROMX

LeagueRoomAnim:
	ld a, [de]
	inc de
	and a
	jr nz, LeagueRoomPaletteAnim
; tile animation
	ld h, d
	ld l, e
	ld e, [hl]
	inc hl
	ld d, [hl] ; de = VRAM destination
	inc hl
	ld c, [hl] ; step mask
	inc hl
	ld b, [hl] ; speed
	inc hl
	push hl
	push de
; 16-bit frame counter: hVBlankCounter plus a high byte that counts its
; wraps, so long sequences (up to 256 steps) can run slowly.
	ldh a, [hVBlankCounter]
	ld e, a
	ld hl, wLeagueAnimLastVBlank
	cp [hl] ; carry: the counter wrapped since the last call
	ld [hl], a
	ld a, [wLeagueAnimCounterHi]
	adc 0
	ld [wLeagueAnimCounterHi], a
	ld d, a
	inc b
.shift
	dec b
	jr z, .got_step
	srl d
	rr e
	jr .shift
.got_step
	ld a, e
	and c
	pop de ; VRAM destination
	pop hl ; -> frames, sequence
	push de
	ld e, a
	ld a, [hli]
	ld c, a
	ld a, [hli]
	ld b, a ; bc = frames
	ld a, [hli]
	ld h, [hl]
	ld l, a ; hl = sequence
	ld d, 0
	add hl, de
	ld l, [hl]
	ld h, 0
	add hl, hl
	add hl, hl
	add hl, hl
	add hl, hl
	add hl, bc ; hl = frame
	pop de
	ld c, LEN_2BPP_TILE
.copy
	ld a, [hli]
	ld [de], a
	inc de
	dec c
	jr nz, .copy
	ret

LeagueRoomPaletteAnim:
; de -> palette, mode. Only the hardware palette changes: wBGPals1/2 keep
; the authored colours, so fades, text boxes and reloads start from them.
	ldh a, [hCGB]
	and a
	ret z
	ldh a, [rBGP]
	cp %11100100
	ret nz
	ld a, [de]
	inc de
	add a
	add a
	add a
	ld b, a ; b = palette * 8 (byte offset into wBGPals1)
	or 1 << rBGPI_AUTO_INCREMENT
	ldh [rBGPI], a
	ld a, [de]
	ld e, a ; mode

	ldh a, [rSVBK]
	push af
	ld a, BANK(wBGPals1)
	ldh [rSVBK], a

	ld a, e
	and a
	jr z, .rotate
	ld hl, .PulsePattern
	ldh a, [hVBlankCounter]
	dec e
	jr z, .got_pattern
	ld hl, .FlickerPattern
	dec e
	jr z, .got_pattern
	srl a ; LEAGUE_PAL_FLICKER_SLOW
.got_pattern
	rrca
	rrca
	and %1111
	add l
	ld l, a
	adc h
	sub l
	ld h, a
	ld e, [hl]
	call .WriteColor
	jr .done

.rotate
; wSilentCryptPulseTimer doubles as the phase counter (0-2); only one of
; these maps (or Silent Crypt) can be loaded at a time.
	ld hl, wSilentCryptPulseTimer
	ld a, [hl]
	inc a
	cp 3
	jr c, .store
	xor a
.store
	ld [hl], a
	ld e, a
	call .WriteColor
	inc e
	call .WrapWrite
	inc e
	call .WrapWrite
.done
	pop af
	ldh [rSVBK], a
	ret

.WrapWrite:
	ld a, e
	cp 3
	jr c, .WriteColor
	sub 3
	ld e, a
.WriteColor:
; write colour e of palette (b / 8) from wBGPals1 to the next BGPD slot
	ld a, e
	add a
	add b
	add LOW(wBGPals1)
	ld l, a
	ld a, HIGH(wBGPals1)
	adc 0
	ld h, a
	ld a, [hli]
	ldh [rBGPD], a
	ld a, [hl]
	ldh [rBGPD], a
	ret

.PulsePattern:
	db 0, 0, 0, 0, 1, 1, 2, 2, 2, 2, 2, 1, 1, 0, 0, 0
.FlickerPattern:
	db 0, 0, 1, 0, 0, 0, 1, 1, 0, 1, 0, 0, 0, 1, 0, 1

