def primary(result):return [r for r in result['checkpoints'] if r['primary']]

def grind_estimate(row,method='lowest',seed=91,limit=20000):
    team=[party_new(dict(species=sp,level=level_of(x,g),growth=g,join_map='CherrygroveCity')) for sp,x,g in zip(row['species'],row['exp_totals'],row['growths'])]
    for m,x in zip(team,row['exp_totals']):m['exp']=x
    goal=row['target_level'];battles=0;waste=0
    while any(level_of(m['exp'],m['growth'])<goal for m in team) and battles<limit:
        w=wild_draw(row['wild_map'],battles,seed,row['badges']>=4)
        if w is None:return None,None
        _,lost,_=give(team,w,row['hard_cap'],method,battles,share_available=row['badges']>=6,trainer=False)
        waste+=lost;battles+=1
    return (battles if battles<limit else None),waste

def catalog_bosses():
    class_stat={}
    for value,cl in re.findall(r'^\s*dw\s+(\d+)\s*;\s*(\w+)',read('data/trainers/stat_exp.asm'),re.M):class_stat[cl]=int(value)
    rows=[]
    for e in EVENTS:
        p=PARTIES[e['party_key']]
        if not e['primary'] and p['group'] not in ['Crystal','Rival1','Rival2','Proton','Petrel','PetrelDirector','Archer','Ariana','Mysticalman','Elder','KarateKing']:continue
        stage=e['stage'];ace=max(m['level'] for m in p['mons'])
        for i,mon in enumerate(p['mons']):
            s=SP[mon['species']];slot=mon['ability_slot']
            ability=s['abilities'][int(slot[-1])-1] if re.fullmatch(r'ABILITY_[123]',slot) else 'generated by trainer engine'
            stat_exp=class_stat.get(e['trainer_class'],0)
            bonus=math.isqrt(stat_exp)//4
            rows.append(dict(milestone=STAGES[stage] if e['primary'] else f'{e["name"]} ({e["map"]})',event_id=e['event_id'],stage=stage,map=e['map'],trainer_class=e['trainer_class'],party_key=p['key'],party_size=len(p['mons']),primary=e['primary'],hard_cap=cap_for(stage) if stage<16 else 100,boss_ace=ace,pokemon_slot=i+1,**mon,stats=s['stats'],bst=s['bst'],types=s['types'],ability=ability,hard_mode_stat_exp=stat_exp,stat_exp_points=bonus,approx_stat_bonus=bonus*mon['level']//100,access_requirements=e['requirements'],event_source=e['source']))
    write_csv('boss_teams.csv',rows)
    return rows

def main():
    start=time.time();export_catalog();bosses=catalog_bosses()
    baseline={};allrows=[];individual=[];zones=[];events=[];runs=0
    for cohort,team in [('mixed_starter',DEFAULT_TEAM),('mixed_alternative',ALT_TEAM)]:
        for style,size,method in itertools.product(PLAYSTYLES,range(1,7),METHODS):
            r=simulate(size,style,method,team_specs=team)
            runs+=1
            for collection,key in [(allrows,'checkpoints'),(individual,'individual')]:
                collection.extend(dict(cohort=cohort,**x) for x in r[key])
            if cohort=='mixed_starter':
                baseline[f'{style}:{size}:{method}']=r
                if method in ['casual','equal_rotation','lowest']:
                    zones.extend(dict(playstyle=style,team_size=size,method=method,**x) for x in r['zones'])
                    events.extend(dict(playstyle=style,team_size=size,method=method,**x) for x in r['events'])
        print(f'Baseline cohort {cohort}: {runs} simulations',flush=True)
    write_csv('team_progression.csv',allrows)
    write_csv('individual_progression.csv',individual)
    write_csv('zone_progression.csv',zones)
    write_csv('battle_ledger.csv',events)
    # Separate convenience files preserve playstyles rather than blending them.
    for style in PLAYSTYLES:
        write_csv(f'progression_{style}.csv',[x for x in allrows if x['playstyle']==style and x['cohort']=='mixed_starter' and x['primary']])
    (HERE/'baseline_results.json').write_text(json.dumps({key:primary(val) for key,val in baseline.items()},indent=2))
    del allrows,individual,zones,events
    sensitivity=[]
    for n,method,wild,seed in itertools.product([4,6],['casual','equal_rotation'],[0,2,5],range(20)):
        r=simulate(n,'typical',method,seed,wild,details=False);runs+=1
        sensitivity.extend(r['checkpoints'])
    write_csv('travel_exploration_sensitivity.csv',sensitivity)
    bands=[]
    for n,method,wild in itertools.product([4,6],['casual','equal_rotation'],[0,2,5]):
        for name in STAGES:
            rows=[x for x in sensitivity if x['team_size']==n and x['method']==method and x['wild_kos_per_map']==wild and x['milestone']==name]
            if rows:bands.append(dict(team_size=n,method=method,wild_kos_per_map=wild,milestone=name,scenarios=len(rows),average_min=min(x['average_level'] for x in rows),average_median=statistics.median(x['average_level'] for x in rows),average_max=max(x['average_level'] for x in rows),deficit_min=min(x['target_shortfall'] for x in rows),deficit_max=max(x['target_shortfall'] for x in rows)))
    write_csv('sensitivity_bands.csv',bands);del sensitivity
    print(f'Seed/travel sensitivities complete: {runs} simulations',flush=True)
    # All orders in the declared source-informed corridor graph: 3 Johto
    # variants, 144 Kanto variants. Additional movement exploits are not claimed.
    johto=[list(p) for p in itertools.permutations(['Chuck','Jasmine','Pryce']) if p.index('Jasmine')<p.index('Pryce')]
    kanto=[list(p) for p in itertools.permutations(GYMS[8:14]) if p.index('Misty')<min(p.index(x) for x in ['Surge','Erika','Janine','Sabrina'])]
    assert len(johto)==3 and len(kanto)==144
    orderrows=[];order_summary=[]
    for index,(jp,kp) in enumerate(itertools.product(johto,kanto)):
        order=GYMS[:4]+jp+['Clair']+kp+['Blaine','Blue']
        for n,method in itertools.product([4,6],['casual','equal_rotation']):
            r=simulate(n,'typical',method,order=order,details=False);runs+=1
            pr=primary(r)
            orderrows.extend(dict(order_id=index,order=' > '.join(order),**x) for x in pr if x['milestone'] in GYMS)
            order_summary.append(dict(order_id=index,team_size=n,method=method,order=' > '.join(order),worst_gym_gap=max(x['boss_ace']-x['min_level'] for x in pr if x['milestone'] in GYMS),blue_average=next(x['average_level'] for x in pr if x['milestone']=='Blue'),blue_shortfall=next(x['target_shortfall'] for x in pr if x['milestone']=='Blue'),red_average=next(x['average_level'] for x in pr if x['milestone']=='Red Mt Silver'),cumulative_wasted=pr[-1]['cumulative_wasted']))
        if index%100==0:print(f'Gym orders {index+1}/432',flush=True)
    write_csv('gym_order_progression.csv',orderrows);write_csv('gym_order_summary.csv',order_summary)
    finish(baseline,runs,start)

def finish(baseline,runs,start):
    bosses=catalog_bosses()
    supplemental=[];suppindividual=[]
    for n,style,method in itertools.product([4,6],['typical','completionist','efficient'],['casual','equal_rotation']):
        scenarios={
            'old_area_replacement':dict(replacement=dict(species='MAGNEMITE',level=26,join_map='Route38',stage=8)),
            'current_area_replacement':dict(replacement=dict(species='SANDSLASH',level=45,join_map='Route26',stage=8)),
            'eevee20_replacement':dict(replacement=dict(species='EEVEE',level=20,join_map='BillsFamilysHouse',stage=8)),
            'green_chain_before_silver':dict(green_first=True),
            'direct_silver_without_e4_rematch':dict(skip_e4_rematch=True),
            'early_cape_after_erika':dict(early_cape=True),
            'earliest_exploration':dict(early_explore=True),
            'early_eusine_hazard':dict(proposed={'event_stage_overrides':{e['event_id']:3 for e in EVENTS if e['map']=='EcruteakCity'}}),
        }
        for name,kwargs in scenarios.items():
            r=simulate(n,style,method,**kwargs);runs+=1
            supplemental.extend(dict(scenario=name,**x) for x in r['checkpoints'])
            suppindividual.extend(dict(scenario=name,**x) for x in r['individual'])
    write_csv('replacement_and_route_scenarios.csv',supplemental);write_csv('replacement_individual.csv',suppindividual)
    curves=[]
    for rate,n in itertools.product(['GROWTH_FAST','GROWTH_MEDIUM_FAST','GROWTH_MEDIUM_SLOW','GROWTH_SLOW'],range(1,7)):
        specs=[dict(m,growth=rate) for m in DEFAULT_TEAM[:n]]
        r=simulate(n,'typical','equal_rotation',team_specs=specs,details=False);runs+=1
        curves.extend(dict(curve=rate,**x) for x in primary(r))
    write_csv('growth_curve_sensitivity.csv',curves)
    fixes={
        'jasmine_cap32':{'caps':{'5':32}},
        'lighthouse_before_chuck':{'event_stage_overrides':{e['event_id']:4 for e in EVENTS if e['map'].startswith('OlivineLighthouse')}},
        'jasmine_trainers_plus3':{'trainer_level_delta':{'OlivineGym':3}},
        'surge_trainers_plus3':{'trainer_level_delta':{'Route6':3,'VermilionGym':3}},
    }
    # Deliberately test a level retargeting alternative. Its failures and
    # overlevel risks are reported; it is not presented as a validated fix.
    target_aces=[69,69,70,70,70,71,71,72]
    delta={BOSS_KEYS[i]:target-max(m['level'] for m in PARTIES[BOSS_KEYS[i]]['mons']) for i,target in zip(range(21,29),target_aces)}
    for i,target in [(30,73),(31,73),(32,73),(33,73),(34,74),(35,74),(36,75),(37,75),(38,77),(39,75),(40,76),(41,77)]:delta[BOSS_KEYS[i]]=target-max(m['level'] for m in PARTIES[BOSS_KEYS[i]]['mons'])
    fixes['endgame_level_retarget_trial']={'party_level_delta':delta}
    fixes['combined_trial']={**fixes['jasmine_cap32'],**fixes['endgame_level_retarget_trial'],
        'trainer_level_delta':{**fixes['jasmine_trainers_plus3']['trainer_level_delta'],**fixes['surge_trainers_plus3']['trainer_level_delta']}}
    (HERE/'hypotheses.json').write_text(json.dumps(fixes,indent=2))
    trials=[]
    for name,proposal in fixes.items():
        for n,style,method in itertools.product(range(1,7),PLAYSTYLES,['casual','equal_rotation']):
            r=simulate(n,style,method,proposed=proposal,details=False);runs+=1
            original={x['milestone']:x for x in primary(baseline[f'{style}:{n}:{method}'])}
            for row in primary(r):
                old=original[row['milestone']]
                trials.append(dict(proposal=name,**row,original_levels=old['levels'],original_target=old['target_level'],original_average=old['average_level'],average_change=round(row['average_level']-old['average_level'],3),original_shortfall=old['target_shortfall'],shortfall_change=row['target_shortfall']-old['target_shortfall'],original_wasted=old['cumulative_wasted'],waste_change=row['cumulative_wasted']-old['cumulative_wasted']))
    write_csv('hypothetical_changes.csv',trials)
    # Every primary milestone, every team size/playstyle, two distribution
    # policies: both balanced training and keeping the selected policy.
    grind=[]
    for style,n,method in itertools.product(PLAYSTYLES,range(1,7),['casual','equal_rotation']):
        for row in primary(baseline[f'{style}:{n}:{method}']):
            balanced,bw=grind_estimate(row,'lowest');selected,sw=grind_estimate(row,method)
            grind.append(dict(playstyle=style,team_size=n,method=method,milestone=row['milestone'],target=row['target_level'],shortfall=row['target_shortfall'],wild_map=row['wild_map'],pooled_estimate=row['pooled_wild_battles_estimate'],balanced_training_kos=balanced,selected_policy_training_kos=selected,balanced_training_cap_waste=bw,selected_policy_training_cap_waste=sw,scope='independent counterfactual at each unground checkpoint; NEVER sum these KOs across milestones'))
    write_csv('grinding_estimates.csv',grind)
    reps=[]
    for r in REPEATS:
        p=PARTIES[r['party_key']]
        reps.append(dict(**r,party_size=len(p['mons']),levels=[m['level'] for m in p['mons']],solo_hard_exp=p['solo_hard_exp'],requirements=[g['command'] for g in DATA['gates'] if g['map']==r['map'] and g['script'].startswith(r['global_script'])]))
    write_csv('repeatable_exp.csv',reps)
    coverage=dict(species=len(SP),growth_usage={g:sum(s['growth']==g for s in SP.values()) for g in GROWTH},party_definitions=len(PARTIES),trainer_pokemon=sum(len(p['mons']) for p in PARTIES.values()),map_scripts=len(DATA['maps']),map_headers=len(MAP_PLAN),map_edges=len(DATA['edges']),trainer_script_references=len(DATA['references']),campaign_encounter_instances=len(EVENTS),primary_milestones=len(STAGES),boss_encounters=len({r['event_id'] for r in bosses}),repeatable_references=len(REPEATS),grass_surf_slots=len(DATA['wild']),grass_surf_map_time_tables=len({(w['table_label'],w['map'],w['time']) for w in DATA['wild']}),fishing_groups=len({w['group'] for w in DATA['fish']}),fishing_time_slots=len(DATA['fish']),tree_rock_slots=len(DATA['trees']),contest_slots=len(DATA['contests']),static_definitions=len(DATA['static']),scripted_wild_instances=len(STATIC_EVENTS),gifts=len(DATA.get('gifts',[])),simulation_runs=runs,gym_order_schedules=432,gym_order_runs=1728,sources=len(list((HERE/'source_manifest.csv').open()))-1,unclassified_trainer_maps=[n for n,p in MAP_PLAN.items() if p['stage']==99 and any(e['map']==n for e in EVENTS)],elapsed_seconds_this_phase=round(time.time()-start,1))
    (HERE/'coverage.json').write_text(json.dumps(coverage,indent=2))
    print(json.dumps(coverage,indent=2),flush=True)

