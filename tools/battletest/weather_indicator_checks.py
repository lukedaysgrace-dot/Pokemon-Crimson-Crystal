#!/usr/bin/env python3
"""Rendered native battle-menu checks and screenshots for release/debug ROMs.

Uses private SRAM, a party generated by the game, and staged wild encounters
and weather. Menu selections and weather moves run through normal button input.
Does not read or change player saves.
"""
import io
import json
from pathlib import Path

from PIL import Image, ImageDraw

from gameplay_rules_checks import new_game
from probability_checks import call
from runner import Harness, ROOT
from save_menu_checks import begin_native_call
from ui_checks import tile_text, wait


WEATHERS = [('rain', 1, 6), ('sun', 2, 3), ('sandstorm', 3, 7), ('hail', 4, 6)]


def run(rom):
    h = Harness(rom_path=rom)
    m, pb = h.battle.mem, h.pb
    out = ROOT / '.tmpbuild/battle-weather-indicator' / rom.stem
    out.mkdir(parents=True, exist_ok=True)
    captures, checks = [], 0

    def check(ok, text):
        nonlocal checks
        checks += 1
        if not ok:
            pb.screen.image.save(out / 'failure.png')
            raise AssertionError(text + '\n' + tile_text(h) + '\n' + h.where())

    def capture(name):
        image = pb.screen.image.convert('RGB')
        image.save(out / (name + '.png'))
        (out / (name + '.json')).write_text(json.dumps(dict(
            virtual=oam(), hardware=list(pb.memory[0xFE00:0xFE10]),
            lcdc=pb.memory[0xFF40], oam_update=m.read('hOAMUpdate'),
            tiles=list(pb.memory[0, 0x8000:0x8040])), indent=2))
        captures.append((name, image))

    def oam():
        return list(m.read_bytes('wVirtualOAM', 16))

    def visible(palette):
        expected = [136, 28, 3, palette, 136, 20, 2, palette,
                    128, 28, 1, palette, 128, 20, 0, palette]
        return (oam() == expected and list(pb.memory[0xFE00:0xFE10]) == expected
                and pb.memory[0xFF40] & 2 != 0)

    def hidden():
        return oam() == [0] * 16 and not any(pb.memory[0xFE00:0xFE10])

    def move_menu():
        h.press('a', hold=4, wait=60)
        wait(h, lambda: 'RAIN DANCE' in tile_text(h) and 'SUNNY DAY' in tile_text(h))

    def draw_call():
        # The routine-only helper parks with DI. Graphics requests require
        # ordinary VBlank service, so explicitly enable interrupts here.
        begin_native_call(h, 'DrawBattleWeatherIndicator')
        for _ in range(120):
            h.tick()
            if pb.register_file.PC in (0xC0F1, 0xC0F3):
                return
        raise RuntimeError('weather drawing did not return')

    try:
        new_game(h, 0)
        sid = call(h, 'GetPokemonIDFromIndex', HL=h.con.species_index('MEW'))
        for key, value in dict(wPartyCount=0, wMonType=0, wCurPartySpecies=sid,
                               wCurPartyLevel=100, wBattleMode=0, wOptions=0x40).items():
            m.write(key, value)
        call(h, 'TryAddMonToParty')
        moves = [call(h, 'GetMoveIDFromIndex', HL=h.con.moves[name])
                 for name in ('RAIN_DANCE', 'SUNNY_DAY', 'SANDSTORM', 'HAIL')]
        splash = call(h, 'GetMoveIDFromIndex', HL=h.con.moves['SPLASH'])
        m.write_bytes('wPartyMon1Moves', moves)
        m.write_bytes('wPartyMon1PP', [10] * 4)
        sid = call(h, 'GetPokemonIDFromIndex', HL=h.con.species_index('MAGIKARP'))
        for key, value in dict(wTempWildMonSpecies=sid, wCurPartyLevel=100,
                               wOtherTrainerClass=0, wBattleType=0, wBattleMode=0,
                               hCurWeather=0).items():
            m.write(key, value)
        begin_native_call(h, 'StartBattle')
        wait(h, lambda: 'FIGHT' in tile_text(h), advance=True)
        # Private encounter setup: prevent the opponent attacking during the
        # presentation tests; no battle engine or rendering code is patched.
        m.write_bytes('wEnemyMonMoves', [splash, 0, 0, 0])
        m.write_bytes('wEnemyMonPP', [40, 0, 0, 0])
        m.write('wCurEnemyMove', splash)
        m.write('wCurEnemyMoveNum', 0)
        baseline = io.BytesIO()
        pb.save_state(baseline)

        def reset(weather=0, duration=5):
            baseline.seek(0)
            pb.load_state(baseline)
            h.text_overflows = []
            h.battle.textbox_contexts.clear()
            m.write('wBattleWeather', weather)
            m.write('wWeatherCount', duration)

        # All possible flags/types: reject none, end-message types and Cloud
        # Nine suppression, and never disturb other objects or battle tiles.
        for raw in range(256):
            reset(raw)
            m.write_bytes('wVirtualOAM', [0x55] * 16)
            m.write_bytes('wVirtualOAM', [17, 18, 19, 20], 16)
            bg = bytes(m.read_bytes('wTileMap', 360))
            draw_call()
            effective = raw & 7
            expected = 1 <= effective <= 4 and not raw & 128
            check(visible(WEATHERS[effective - 1][2]) if expected else hidden(),
                  f'weather byte {raw:#04x}: effective weather indicator')
            check(m.read_bytes('wVirtualOAM', 4, 16) == bytes([17, 18, 19, 20]),
                  f'weather byte {raw:#04x}: unrelated OAM preserved')
            check(bytes(m.read_bytes('wTileMap', 360)) == bg,
                  f'weather byte {raw:#04x}: background preserved')
            check(m.read('wBattleWeather') == raw and m.read('wWeatherCount') == 5,
                  f'weather byte {raw:#04x}: gameplay weather/timer unchanged')
            check(m.read('hOAMUpdate') == 1, f'weather byte {raw:#04x}: OAM scheduling restored')

        for side in ('player', 'enemy'):
            reset(1)
            m.write('wPlayerAbility', h.con.ability_id('CLOUD_NINE' if side == 'player' else 'NO_ABILITY'))
            m.write('wEnemyAbility', h.con.ability_id('CLOUD_NINE' if side == 'enemy' else 'NO_ABILITY'))
            call(h, 'RefreshWeatherSuppression')
            draw_call()
            check(m.read('wBattleWeather') == 0x81 and hidden(),
                  side + ': actual Cloud Nine refresh hides rain without deleting it')
            m.write('wPlayerAbility', 0)
            m.write('wEnemyAbility', 0)
            call(h, 'RefreshWeatherSuppression')
            draw_call()
            check(m.read('wBattleWeather') == 1 and visible(6),
                  side + ': removing Cloud Nine restores underlying rain icon')

        for scheduling in (0, 1):
            reset(2)
            m.write('hOAMUpdate', scheduling)
            draw_call()
            check(visible(3) and m.read('hOAMUpdate') == scheduling,
                  f'OAM scheduling {scheduling}: visible icon and exact restoration')

        reset()
        move_menu()
        check(hidden(), 'no weather: no move-menu icon')
        capture('clear-move-menu')

        for name, weather, palette in WEATHERS:
            reset(weather)
            move_menu()
            check(visible(palette), name + ': correct native move-menu OAM')
            capture(name + '-move-menu')
            # The uploaded pixels must be exactly the corresponding ROM art.
            bank, address = h.sym['Battle' + {'rain': 'Rain', 'sun': 'Sun',
                                            'sandstorm': 'Sand', 'hail': 'Hail'}[name] + 'Icon']
            expected = bytes(pb.memory[bank, address:address + 64])
            check(bytes(pb.memory[0, 0x8000:0x8040]) == expected, name + ': exact icon tiles')
            h.press('down', hold=4, wait=30)
            check(visible(palette), name + ': cursor movement retains icon')
            h.press('select', hold=4, wait=30)
            check(visible(palette), name + ': move-reorder marker retains icon')
            h.press('b', hold=4, wait=60)
            wait(h, lambda: 'FIGHT' in tile_text(h))
            check(visible(palette), name + ': command-menu icon')
            capture(name + '-command-menu')
            h.press('down', hold=4, wait=20)  # PACK
            h.press('a', hold=4, wait=100)
            check(not any(oam()[::4]), name + ': no indicator sprites in Pack')
            h.press('b', hold=4, wait=100)
            wait(h, lambda: 'FIGHT' in tile_text(h))
            check(visible(palette), name + ': icon returns from Pack')

        reset(1)
        move_menu()
        m.write('wBattleMonPP', 0)
        warnings = []
        pb.hook_register(*h.sym['MoveSelectionScreen.place_textbox_start_over'],
                         lambda _: warnings.append(oam()), None)
        h.press('a', hold=4, wait=20)
        wait(h, lambda: bool(warnings) and 'RAIN DANCE' in tile_text(h), advance=True)
        check(bool(warnings) and visible(6), 'no-PP warning returns to a visible rain menu')
        check(m.read('wBattleMonPP') == 0 and not h.text_overflows,
              'no-PP rejection preserves PP and text bounds')
        pb.hook_deregister(*h.sym['MoveSelectionScreen.place_textbox_start_over'])

        reset(0x81)
        move_menu()
        check(hidden(), 'suppressed rain: no effective-weather icon')
        capture('cloud-nine-suppressed')
        h.press('b', hold=4, wait=60)
        check(hidden(), 'suppressed rain: no command-menu icon')
        move_menu()
        # An ordinary menu re-entry refreshes the underlying weather after
        # suppression is lifted; no saved display-state field is needed.
        m.write('wBattleWeather', 1)
        h.press('down', hold=4, wait=30)
        check(visible(6), 'rain returns after suppression clears')

        # Real weather moves, with battle scenes on. Observe the actual OAM
        # at the first PlayBattleAnim call after choosing the move.
        animation_oam = []
        pb.hook_register(*h.sym['PlayBattleAnim'], lambda _: animation_oam.append(
            (oam(), list(pb.memory[0xFE00:0xFE10]))), None)
        for slot, (name, weather, palette) in enumerate(WEATHERS):
            reset()
            move_menu()
            for _ in range(slot):
                h.press('down', hold=4, wait=16)
            animation_oam.clear()
            h.press('a', hold=4, wait=20)
            wait(h, lambda: m.read('wBattleWeather') & 7 == weather
                 and 'FIGHT' in tile_text(h), advance=True)
            check(bool(animation_oam), name + ': actual weather animation executed')
            check(animation_oam[0] == ([0] * 16, [0] * 16),
                  name + ': menu and hardware OAM cleared before animation')
            check(visible(palette), name + ': weather move updates command icon')
            check(not h.text_overflows, name + ': text stays within bounds')

        # Weather expiration through a normal full turn removes the icon.
        reset(1, duration=1)
        m.write_bytes('wBattleMonMoves', [splash, *moves[1:]])
        m.write_bytes('wPartyMon1Moves', [splash, *moves[1:]])
        h.press('a', hold=4, wait=60)
        wait(h, lambda: 'SPLASH' in tile_text(h))
        h.press('a', hold=4, wait=20)
        wait(h, lambda: m.read('wBattleWeather') & 7 == 0 and 'FIGHT' in tile_text(h), advance=True)
        check(hidden(), 'natural rain expiration removes command icon')
        capture('rain-ended')

        canvas = Image.new('RGB', (160 * 4, 166 * ((len(captures) + 3) // 4)), '#eef0f2')
        draw = ImageDraw.Draw(canvas)
        for i, (name, image) in enumerate(captures):
            x, y = i % 4 * 160, i // 4 * 166
            draw.text((x + 3, y + 4), name.replace('-menu', ''), fill='#17212b')
            canvas.paste(image, (x, y + 22))
        canvas.resize((canvas.width * 2, canvas.height * 2), Image.Resampling.NEAREST).save(out / 'contact.png')

        # A compact user-facing gallery: every actual command/move screen,
        # in a fixed weather order. Only margins/labels are added to captures.
        gallery = Image.new('RGB', (160 * 4, 166 * 2), '#eef0f2')
        labels = ImageDraw.Draw(gallery)
        images = dict(captures)
        for row, kind in enumerate(('command', 'move')):
            for column, (name, _, _) in enumerate(WEATHERS):
                x, y = column * 160, row * 166
                labels.text((x + 3, y + 4), name.title() + ' / ' + kind, fill='#17212b')
                gallery.paste(images[name + '-' + kind + '-menu'], (x, y + 22))
        gallery.resize((1280, 664), Image.Resampling.NEAREST).save(out / 'weather-menus.png')
        result = dict(rom=rom.name, checks=checks, screenshots=len(captures), failures=0)
        (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
        print(json.dumps(result), flush=True)
    finally:
        pb.stop(save=False)


if __name__ == '__main__':
    import sys
    for rom in [Path(p) for p in sys.argv[1:]] or [ROOT / 'pokecrystal.gbc', ROOT / 'pokecrystal_debug.gbc']:
        run(rom)
