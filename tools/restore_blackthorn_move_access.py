#!/usr/bin/env python3
"""Restore every verified move, using Blackthorn for otherwise absent access."""
import json
from pathlib import Path

from audit_breeding_moves import breeding_data
from audit_canonical_learnsets import RECEIPT, available
from audit_learnset_variety import ROOT


def main():
    receipt = json.loads(RECEIPT.read_text(encoding='utf-8'))
    data = breeding_data()
    order, _, _, eggs, *_ = data
    # Decide placement without any fallback tutor seeds. Existing natural,
    # breeding, machine, utility and evolution access always takes priority.
    base = available(data, technical={})
    original = available(data, technical=receipt['retired_technical_tutor'])
    protected = receipt.get('protected_move_access', {c: sorted(ms) for c, ms in original.items()})
    technical = {c: sorted(set(receipt['expected'].get(c, []))-base[c]) for c in order}
    after = available(data, technical=technical)
    for c in order:
        assert set(protected[c]) <= after[c], (c, 'lost previously expanded access', set(protected[c])-after[c])
        assert set(receipt['expected'].get(c, [])) <= after[c], (c, 'unrestored canonical access')
        assert len(set(eggs[c]) | set(technical[c])) <= 192, (c, 'Blackthorn menu too long')
        if c.endswith('_CLONE'):
            assert technical[c] == technical[c[:-6]], (c, 'clone fallback mismatch')
    lines = ['; Generated by tools/restore_blackthorn_move_access.py.',
             '; Blackthorn only: verified moves without another acquisition route.',
             '; Goldenrod retains its original five utility moves.',
             'SECTION "Technical Tutor Pointers", ROMX', 'TechnicalTutorPointers::']
    groups, labels = {}, {}
    for c in order:
        key = tuple(technical[c])
        if key not in groups:
            groups[key] = 'TechnicalTutor_' + (c if key else 'None')
        labels[c] = groups[key]
        lines.append(f'\tdba {labels[c]} ; {c}')
    lines.append('assert (@ - TechnicalTutorPointers) == NUM_POKEMON * 3')
    for i, (moves, label) in enumerate(groups.items()):
        if i % 100 == 0:
            lines += ['', f'SECTION "Blackthorn Tutor Moves {i // 100 + 1}", ROMX']
        lines += ['', label+':'] + [f'\tdw {m}' for m in moves] + ['\tdw 0']
    (ROOT/'data/pokemon/technical_tutor.asm').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    receipt['previously_deferred_moves'] = receipt.get('previously_deferred_moves', receipt.get('deferred_moves', {}))
    receipt['deferred_moves'] = {}
    receipt['protected_move_access'] = protected
    receipt['distribution_revision'] = 'full-access-with-blackthorn-fallback'
    receipt['changes']['technical_tutor'] = {c: ms for c, ms in technical.items() if ms}
    receipt['fallback_tutor'] = {'location': 'Blackthorn City, Move Deleter\'s House',
                                'npc': 'Existing purple move tutor', 'fee': 5000,
                                'policy': 'Existing egg menu plus species-specific verified fallback moves'}
    receipt['policy'] = ('Preserve every verified move and all previously expanded move access. Keep natural/thematic level-up, '
                         'canonical breeding and existing machine routes. Teach every remaining verified compatible move through '
                         'the existing Blackthorn move tutor. Goldenrod remains limited to its original five utility moves. '
                         'No supported move is excluded for lacking a thematic natural or egg placement.')
    RECEIPT.write_text(json.dumps(receipt, indent=2)+'\n', encoding='utf-8')
    print('Blackthorn fallback assignments:', sum(map(len, technical.values())))
    print('Largest combined Blackthorn menu:', max((len(set(eggs[c]) | set(technical[c])), c) for c in order))
    print('Protected species/move access pairs:', sum(map(len, protected.values())))
    print('All prior access preserved; all implemented canonical pairs available; zero deferred.')


if __name__ == '__main__':
    main()
