#!/usr/bin/env python3
"""Regenerate the five Elite Four chamber tilesets and maps from source art.

Writes, for each chamber: gfx/tilesets/<room>.png and .pal,
data/tilesets/<room>_{metatiles,attributes}.bin and _collision.asm,
maps/<Room>.ablk, and rewrites the door/gate `changeblock` block IDs in
maps/<Room>.asm. Previews (with collision overlays) go to
_artifacts/league-rooms-art/. Requires numpy and Pillow.

    python3 tools/e4_rooms/build_all.py
"""
import importlib
import json
import re
import runpy
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from e4kit import ROOT, OUT  # noqa: E402

ROOMS = [
    # script, tileset, map, gate (x, y), door (x, y), gate comment, door comment
    ('koga', 'kogas_room', 'KogasRoom', (4, 14), (4, 2), 'sliding doors slam shut', 'doors slide open'),
    ('bruno', 'brunos_room', 'BrunosRoom', (4, 14), (4, 2), 'boulder seals the tunnel', 'stone seal opens'),
    ('karen', 'karens_room', 'KarensRoom', (4, 14), (4, 2), 'iron gate closes', 'archway doors open'),
    ('lorelei', 'loreleis_room', 'LoreleisRoom', (4, 14), (4, 2), 'ice wall seals the way', 'ice door opens'),
    ('lance', 'lances_room', 'LancesRoom', (4, 22), (4, 0), 'dragon gate closes', "the dragon's jaws open"),
]


MODES = {'ROTATE': 'LEAGUE_PAL_ROTATE', 'PULSE': 'LEAGUE_PAL_PULSE', 'FLICKER': 'LEAGUE_PAL_FLICKER',
         'FLICKER_SLOW': 'LEAGUE_PAL_FLICKER_SLOW'}


def write_anims(rooms_info):
    head = ['; Generated by tools/e4_rooms/build_all.py - do not edit.', '']
    data, tables = list(head), list(head)
    for mapname, info in rooms_info:
        entries = []
        for a in info.get('anims', []):
            lab = f"LeagueAnim_{mapname}_{a['name']}"
            n = len(a['seq'])
            data += [f'{lab}:', '\tdb LEAGUE_ANIM_TILE', f"\tdw vTiles2 tile ${a['tile']:02x}",
                     f"\tdb {n - 1}, {a['shift']}", f'\tdw {lab}Frames, {lab}Seq',
                     f'{lab}Seq:', '\tdb ' + ', '.join(str(v) for v in a['seq']), f'{lab}Frames:']
            for fr in a['frames']:
                bs = bytes.fromhex(fr)
                data.append('\tdb ' + ', '.join(f'${v:02x}' for v in bs))
            data.append('')
            entries.append(lab)
        for i, (pal, mode) in enumerate(info.get('pal_anims', [])):
            lab = f'LeagueAnim_{mapname}_Palette{i}'
            data += [f'{lab}:', f'\tdb LEAGUE_ANIM_PALETTE, {pal}, {MODES[mode]}', '']
            entries.append(lab)
        tables.append(f'Tileset{mapname}Anim:')
        for lab in entries:
            tables.append(f'\tdw {lab}, LeagueRoomAnimTrampoline')
        if not entries:
            tables.append('\tdw NULL, WaitTileAnimation')
        tables += ['\tdw NULL, DoneTileAnimation', '']
    Path(ROOT, 'data/tilesets/league_room_anims.asm').write_text('\n'.join(data) + '\n')
    Path(ROOT, 'data/tilesets/league_room_anim_tables.asm').write_text('\n'.join(tables) + '\n')


def main():
    rooms_info = []
    for script, tileset, mapname, gate, door, gtxt, dtxt in ROOMS:
        runpy.run_path(str(HERE / f'{script}.py'), run_name='__main__')
        info = json.loads(Path(OUT, f'{tileset}.json').read_text())
        assert info['tiles'] <= 255, f'{tileset}: {info["tiles"]} tiles (limit 255)'
        path = Path(ROOT, 'maps', f'{mapname}.asm')
        text = path.read_text()
        text = re.sub(r'changeblock %d, %d, \$[0-9a-f]+[^\n]*' % gate,
                      'changeblock %d, %d, $%02x ; %s' % (*gate, info['extras']['gate_closed'], gtxt), text)
        text = re.sub(r'changeblock %d, %d, \$[0-9a-f]+[^\n]*' % door,
                      'changeblock %d, %d, $%02x ; %s' % (*door, info['extras']['door_open'], dtxt), text)
        path.write_text(text)
        rooms_info.append((mapname, info))
    write_anims(rooms_info)
    print('All five Elite Four chambers regenerated.')


if __name__ == '__main__':
    main()
