#!/usr/bin/env python3
"""Generate the reminder's immediate-ancestor table from actual evolution rows."""
from pathlib import Path
import argparse

from audit_learnset_variety import load_sources

ROOT = Path(__file__).resolve().parents[1]


def generate():
    order, _, _, _, parents, _ = load_sources()
    lines = ['; Generated by tools/generate_pre_evolutions.py. Do not edit by hand.',
             '; Immediate predecessor, or 0 for a species with no pre-evolution.',
             'PreEvolutionSpecies::']
    for species in order:
        chain = set()
        ancestor = species
        while parents[ancestor]:
            choices = set(parents[ancestor])
            assert len(choices) == 1, (ancestor, 'ambiguous ancestry', choices)
            ancestor = choices.pop()
            assert ancestor not in chain, (species, 'evolution cycle')
            chain.add(ancestor)
        choices = set(parents[species])
        lines.append(f'\tdw {next(iter(choices)) if choices else "0"} ; {species}')
    lines += ['assert (@ - PreEvolutionSpecies) == NUM_POKEMON * 2', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'data/pokemon/pre_evolutions.asm'
    content = generate()
    if args.check:
        assert path.read_text(encoding='utf-8') == content, 'Regenerate data/pokemon/pre_evolutions.asm'
        print('Pre-evolution table matches every evolution row.')
    else:
        path.write_text(content, encoding='utf-8')
        print(f'Wrote {path}')


if __name__ == '__main__':
    main()
